def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def patch(text, old, new, count=1):
    found = text.count(old)
    if found != count:
        raise SystemExit(f"expected {count} occurrence(s), found {found}:\n{old}")
    return text.replace(old, new)


def segment(text, start, end):
    """Split text into before, the part from start up to end, and after."""
    if text.count(start) != 1:
        raise SystemExit(f"segment start not unique: {start}")
    head, rest = text.split(start, 1)
    if end not in rest:
        raise SystemExit(f"segment end not found: {end}")
    body, tail = rest.split(end, 1)
    return head, start + body, end + tail


SPLIT_HEADER = r'''// Generated by scripts/diagnostics/build_variance_diagnostics.py.
// Diagnostic recording of queue wait and service time; not part of the engine.
#pragma once
#include <cstdint>
#include <cstdio>
#include <vector>
#include <algorithm>
#include <sched.h>
#include <sys/resource.h>
#include <x86intrin.h>

namespace mm_diag {

inline constexpr std::size_t kCap = 200'000;
inline constexpr std::uint32_t kNoDepth = 0xffffffffu;
// Allocated and zeroed at start-up, so recording adds no page faults to a run.
inline std::vector<std::uint64_t> g_push(kCap), g_pop(kCap), g_done(kCap);
inline std::vector<std::uint32_t> g_depth(kCap);
// Written by the consumer; read by the main thread after join.
inline std::size_t g_count = 0;

enum Role { kConsumer = 0, kProducer = 1 };
struct ThreadInfo {
    int cpu_begin = -1, cpu_end = -1;
    std::uint64_t tsc_begin = 0, tsc_end = 0;
    long nvcsw = 0, nivcsw = 0;
};
inline ThreadInfo g_threads[2];

class ThreadProbe {
public:
    explicit ThreadProbe(Role role) : role_(role) {
        rusage u{};
        getrusage(RUSAGE_THREAD, &u);
        nvcsw_ = u.ru_nvcsw;
        nivcsw_ = u.ru_nivcsw;
        g_threads[role_].cpu_begin = sched_getcpu();
        g_threads[role_].tsc_begin = __rdtsc();
    }
    ~ThreadProbe() {
        ThreadInfo& t = g_threads[role_];
        t.tsc_end = __rdtsc();
        t.cpu_end = sched_getcpu();
        rusage u{};
        getrusage(RUSAGE_THREAD, &u);
        t.nvcsw = u.ru_nvcsw - nvcsw_;
        t.nivcsw = u.ru_nivcsw - nivcsw_;
    }
    ThreadProbe(const ThreadProbe&) = delete;
    ThreadProbe& operator=(const ThreadProbe&) = delete;

private:
    Role role_;
    long nvcsw_ = 0, nivcsw_ = 0;
};

inline void reset() {
    g_count = 0;
    g_threads[0] = ThreadInfo{};
    g_threads[1] = ThreadInfo{};
}

inline void record(std::uint64_t push, std::uint64_t pop, std::uint64_t done, std::uint32_t depth) {
    const std::size_t i = g_count;
    if (i < kCap) {
        g_push[i] = push;
        g_pop[i] = pop;
        g_done[i] = done;
        g_depth[i] = depth;
        g_count = i + 1;
    }
}

// Same index rule as LatencyRecorder::report.
template <typename T>
inline T at(std::vector<T>& sorted, double p) {
    return sorted[static_cast<std::size_t>(p * (sorted.size() - 1))];
}

// Push and pop are read on different cores; a difference below zero is
// counted and recorded as 0 rather than wrapped.
inline std::size_t g_negative = 0;
inline std::uint64_t later(std::uint64_t end, std::uint64_t start) {
    if (end >= start) return end - start;
    ++g_negative;
    return 0;
}

inline void print_split(const char* label) {
    const std::size_t n = g_count;
    if (n < 2) {
        std::printf("MM_SPLIT label=%s n=%zu\n", label, n);
        return;
    }
    g_negative = 0;
    std::vector<std::uint64_t> wait(n), service(n), e2e(n), depth;
    std::uint64_t e2e_max = 0, consumer_stall = 0, empty_wait = 0;
    std::size_t e2e_max_at = 0, consumer_stall_at = 0, empty_wait_at = 0;
    for (std::size_t i = 0; i < n; ++i) {
        wait[i] = later(g_pop[i], g_push[i]);
        service[i] = later(g_done[i], g_pop[i]);
        e2e[i] = later(g_done[i], g_push[i]);
        if (e2e[i] > e2e_max) { e2e_max = e2e[i]; e2e_max_at = i; }
        if (g_depth[i] != kNoDepth) depth.push_back(g_depth[i]);
        if (i == 0) continue;
        // Time from finishing one order to taking the next. If the next order
        // was already queued, the consumer was held up; otherwise it waited
        // for the producer.
        const std::uint64_t gap = later(g_pop[i], g_done[i - 1]);
        if (g_push[i] <= g_done[i - 1]) {
            if (gap > consumer_stall) { consumer_stall = gap; consumer_stall_at = i; }
        } else if (gap > empty_wait) {
            empty_wait = gap;
            empty_wait_at = i;
        }
    }
    std::sort(wait.begin(), wait.end());
    std::sort(service.begin(), service.end());
    std::sort(e2e.begin(), e2e.end());
    std::sort(depth.begin(), depth.end());
    const ThreadInfo& c = g_threads[kConsumer];
    const ThreadInfo& p = g_threads[kProducer];
    std::printf("MM_SPLIT label=%s n=%zu", label, n);
    const double ps[] = {0.50, 0.95, 0.99, 0.999};
    const char* names[] = {"p50", "p95", "p99", "p999"};
    for (int k = 0; k < 4; ++k)
        std::printf(" e2e_%s=%llu wait_%s=%llu svc_%s=%llu", names[k],
                    (unsigned long long)at(e2e, ps[k]), names[k], (unsigned long long)at(wait, ps[k]),
                    names[k], (unsigned long long)at(service, ps[k]));
    std::printf(" e2e_max=%llu wait_max=%llu svc_max=%llu e2e_max_at=%zu",
                (unsigned long long)e2e.back(), (unsigned long long)wait.back(),
                (unsigned long long)service.back(), e2e_max_at);
    std::printf(" consumer_stall=%llu consumer_stall_at=%zu empty_wait=%llu empty_wait_at=%zu",
                (unsigned long long)consumer_stall, consumer_stall_at,
                (unsigned long long)empty_wait, empty_wait_at);
    if (!depth.empty())
        std::printf(" depth_p50=%llu depth_p99=%llu depth_max=%llu",
                    (unsigned long long)at(depth, 0.50), (unsigned long long)at(depth, 0.99),
                    (unsigned long long)depth.back());
    std::printf(" consumer_cpu=%d:%d producer_cpu=%d:%d consumer_nvcsw=%ld consumer_nivcsw=%ld"
                " producer_nvcsw=%ld producer_nivcsw=%ld producer_start_after_consumer=%lld"
                " first_push_after_consumer=%lld run=%llu negative=%zu\n",
                c.cpu_begin, c.cpu_end, p.cpu_begin, p.cpu_end, c.nvcsw, c.nivcsw, p.nvcsw, p.nivcsw,
                (long long)(p.tsc_begin - c.tsc_begin), (long long)(g_push[0] - c.tsc_begin),
                (unsigned long long)(c.tsc_end - c.tsc_begin), g_negative);
}

}  // namespace mm_diag
'''


PLACE_HEADER = r'''// Generated by scripts/diagnostics/build_variance_diagnostics.py.
// Diagnostic placement of queue objects; not part of the benchmarks.
#pragma once
#include <atomic>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <new>
#include <sched.h>
#include <sys/mman.h>
#include <benchmark/benchmark.h>

namespace mm_place {

enum Kind { kSpsc = 0, kOrder = 1, kMutex = 2, kKinds = 3 };
inline constexpr int kPlacements = 8;
inline const char* const kNames[kKinds] = {"spsc", "order", "mutex"};
inline void* g_regions[kKinds][kPlacements];

// One region per kind and index, mapped and populated before any benchmark
// runs, in a fixed order, and never released. Each region starts on a page.
inline bool allocate_all(const std::size_t (&bytes)[kKinds]) {
    for (int index = 0; index < kPlacements; ++index) {
        for (int kind = 0; kind < kKinds; ++kind) {
            const std::size_t size = (bytes[kind] + 64 + 4095) / 4096 * 4096;
            void* base = mmap(nullptr, size, PROT_READ | PROT_WRITE,
                              MAP_PRIVATE | MAP_ANONYMOUS | MAP_POPULATE, -1, 0);
            if (base == MAP_FAILED) {
                std::perror("mmap");
                std::abort();
            }
            g_regions[kind][index] = base;
            const auto address = reinterpret_cast<std::uintptr_t>(base);
            std::fprintf(stderr, "MM_PLACE kind=%s index=%d address=%p mod64=%zu mod4096=%zu bytes=%zu\n",
                         kNames[kind], index, base, static_cast<std::size_t>(address % 64),
                         static_cast<std::size_t>(address % 4096), size);
        }
    }
    return true;
}

inline std::size_t mutex_offset(int index) { return static_cast<std::size_t>(index % 4) * 16; }

template <typename T>
inline T& construct(Kind kind, std::int64_t index, std::size_t offset = 0) {
    if (index < 0 || index >= kPlacements) std::abort();
    void* where = static_cast<char*>(g_regions[kind][index]) + offset;
    return *::new (where) T;
}

// Which CPU each role started an iteration on.
inline std::atomic<int> g_consumer_cpu{-1};

struct CpuTally {
    int producer = -1;
    long iterations = 0, same = 0, producer_on_3 = 0;
    void start() { producer = sched_getcpu(); }
    void add() {
        ++iterations;
        same += producer == g_consumer_cpu.load(std::memory_order_relaxed);
        producer_on_3 += producer == 3;
    }
    void report(benchmark::State& state) const {
        if (!iterations) return;
        state.counters["same_cpu"] = static_cast<double>(same) / iterations;
        state.counters["producer_cpu3"] = static_cast<double>(producer_on_3) / iterations;
    }
};

}  // namespace mm_place
'''


