#!/usr/bin/env python3
"""Build the diagnostic programs of the variance-sources study.

Each program is generated from an unchanged benchmark source by exact text
replacements, every one of which must match the expected number of times, and
is compiled with the flags and link inputs of the Release tree. Added lines end
in "// DIAG". The generated sources, commands and hashes are written beside the
binaries in build/diagnostics/variance/.

bench_pipeline_split   bench_matching_engine.cpp and src/matching_engine.cpp.
                       The consumer also reads the TSC when it takes an order
                       out of the queue, so the printed latency splits into
                       queue wait and service time. Each latency report is
                       followed by an MM_SPLIT line.
bench_mutex_split      bench_baseline_mutex.cpp, with the same split and the
                       number of orders left in the queue at each pop.
bench_queue_placement  bench_spsc_ring_buffer.cpp. The two-thread benchmarks
                       take a second argument, a placement index 0-7, and put
                       their queue in one of eight memory regions mapped and
                       populated at start-up. The mutex benchmark puts its
                       queue, mutex, flag and sum at byte 0, 16, 32 or 48 of
                       its region (index % 4). Each region is one MM_PLACE line.

Requires an already built CMake Unix Makefiles Release tree.
"""

