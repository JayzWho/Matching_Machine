def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def patch(text, old, new, count=1):
    found = text.count(old)
    if found != count:
        raise SystemExit(f"expected {count} occurrence(s), found {found}:\n{old}")
    return text.replace(old, new)


def segment(text, start, end):
    """Split text into before, the part from start up to end, and after."""
    if text.count(start) != 1:
        raise SystemExit(f"segment start not unique: {start}")
    head, rest = text.split(start, 1)
    if end not in rest:
        raise SystemExit(f"segment end not found: {end}")
    body, tail = rest.split(end, 1)
    return head, start + body, end + tail


HEADER = r'''// Generated by scripts/diagnostics/build_queue_regimes.py.
// Diagnostic placement of queue objects, retry counts, a ring that caches the
// other side's index, and cache-line round trips; not part of the benchmarks.
#pragma once
#include <algorithm>
#include <array>
#include <atomic>
#include <chrono>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <new>
#include <thread>
#include <pthread.h>
#include <sched.h>
#include <sys/mman.h>
#include <benchmark/benchmark.h>

namespace mm_regime {

enum Kind { kSpsc = 0, kOrder = 1, kOrderSource = 2, kMutex = 3, kLocals = 4, kKinds = 5 };
inline constexpr int kPlacements = 8;
inline const char* const kNames[kKinds] = {"spsc", "order", "order_source", "mutex", "locals"};
inline void* g_regions[kKinds][kPlacements];

// One region per kind and index, mapped and populated before any benchmark
// runs, in a fixed order, and never released. Each region starts on a page.
inline bool allocate_all(const std::size_t (&bytes)[kKinds]) {
    for (int index = 0; index < kPlacements; ++index) {
        for (int kind = 0; kind < kKinds; ++kind) {
            const std::size_t size = (bytes[kind] + 64 + 4095) / 4096 * 4096;
            void* base = mmap(nullptr, size, PROT_READ | PROT_WRITE,
                              MAP_PRIVATE | MAP_ANONYMOUS | MAP_POPULATE, -1, 0);
            if (base == MAP_FAILED) {
                std::perror("mmap");
                std::abort();
            }
            g_regions[kind][index] = base;
            std::fprintf(stderr, "MM_PLACE kind=%s index=%d address=%p bytes=%zu\n",
                         kNames[kind], index, base, size);
        }
    }
    return true;
}

// Builds an object at the start of a region. Benchmarks with the same index
// reuse the same region, one after another.
template <typename T>
inline T& construct(Kind kind, std::int64_t index) {
    if (index < 0 || index >= kPlacements) std::abort();
    return *::new (g_regions[kind][index]) T;
}

template <typename T>
inline T* construct_array(Kind kind, std::int64_t index, std::int64_t n) {
    if (index < 0 || index >= kPlacements) std::abort();
    T* first = static_cast<T*>(g_regions[kind][index]);
    for (std::int64_t i = 0; i < n; ++i) ::new (static_cast<void*>(first + i)) T();
    return first;
}

// The retries of one side during one transfer: fail(done) is called for every
// try that found the queue empty (consumer) or full (producer), with the number
// of items that side has completed. A local, so it stays in registers; it adds
// no instruction to a successful try.
struct Probe {
    std::int64_t fails = 0;  // tries that found the queue empty or full
    std::int64_t waits = 0;  // items before which the side had to retry
    std::int64_t last = -1;
    void fail(std::int64_t done) noexcept {
        ++fails;
        if (done != last) {
            last = done;
            ++waits;
        }
    }
};

// Which CPU the consumer started an iteration on.
inline std::atomic<int> g_consumer_cpu{-1};

// Over one benchmark call: the probes of every iteration, the queue depth when
// the producer finished, and where the two threads started.
struct Tally {
    int producer = -1;
    double iterations = 0, pop_fails = 0, pop_waits = 0, push_fails = 0, push_waits = 0;
    double depth_end = 0, same = 0, producer_high = 0;
    void start() { producer = sched_getcpu(); }
    void add(const Probe& pop, const Probe& push, std::size_t depth, std::int64_t n) {
        const int consumer = g_consumer_cpu.load(std::memory_order_relaxed);
        iterations += 1;
        pop_fails += static_cast<double>(pop.fails);
        pop_waits += static_cast<double>(pop.waits);
        push_fails += static_cast<double>(push.fails);
        push_waits += static_cast<double>(push.waits);
        depth_end += static_cast<double>(depth) / n;
        same += producer == consumer;
        producer_high += producer > consumer;
    }
    void report(benchmark::State& state, std::int64_t n) const {
        if (!iterations) return;
        const double items = iterations * static_cast<double>(n);
        state.counters["pop_fails"] = pop_fails / items;
        state.counters["pop_waits"] = pop_waits / items;
        state.counters["push_fails"] = push_fails / items;
        state.counters["push_waits"] = push_waits / items;
        state.counters["depth_end"] = depth_end / iterations;
        state.counters["same_cpu"] = same / iterations;
        state.counters["producer_cpu_high"] = producer_high / iterations;
    }
};

// SPSCRingBuffer with one change: each side keeps a copy of the other side's
// index next to its own and reads the other side's index only when the copy
// says the queue is full (producer) or empty (consumer). head_ and tail_ stay
// on lines 0 and 1 and the slots start on line 2, as in SPSCRingBuffer.
template <typename T, std::size_t Capacity>
class CachedRing {
    static_assert((Capacity & (Capacity - 1)) == 0, "Capacity must be a power of 2");

public:
    bool try_push(const T& item) noexcept {
        const std::size_t tail = tail_.load(std::memory_order_relaxed);
        const std::size_t next_tail = (tail + 1) & kMask;
        if (next_tail == head_cache_) {
            head_cache_ = head_.load(std::memory_order_acquire);
            if (next_tail == head_cache_) return false;
        }
        buffer_[tail] = item;
        tail_.store(next_tail, std::memory_order_release);
        return true;
    }
    bool try_pop(T& item) noexcept {
        const std::size_t head = head_.load(std::memory_order_relaxed);
        if (head == tail_cache_) {
            tail_cache_ = tail_.load(std::memory_order_acquire);
            if (head == tail_cache_) return false;
        }
        item = buffer_[head];
        head_.store((head + 1) & kMask, std::memory_order_release);
        return true;
    }
    [[nodiscard]] std::size_t size() const noexcept {
        const std::size_t head = head_.load(std::memory_order_acquire);
        const std::size_t tail = tail_.load(std::memory_order_acquire);
        return (tail - head) & kMask;
    }

private:
    static constexpr std::size_t kMask = Capacity - 1;
    alignas(64) std::atomic<std::size_t> head_{0};
    std::size_t tail_cache_ = 0;  // the consumer's copy of tail_
    alignas(64) std::atomic<std::size_t> tail_{0};
    std::size_t head_cache_ = 0;  // the producer's copy of head_
    alignas(64) std::array<T, Capacity> buffer_{};
};

// The two CPUs the launch may use; the round trips run between them.
inline std::array<int, 2> launch_cpus() {
    cpu_set_t set;
    CPU_ZERO(&set);
    if (sched_getaffinity(0, sizeof(set), &set)) std::abort();
    std::array<int, 2> cpus{-1, -1};
    int found = 0;
    for (int cpu = 0; cpu < CPU_SETSIZE && found < 2; ++cpu)
        if (CPU_ISSET(cpu, &set)) cpus[found++] = cpu;
    if (found != 2 || CPU_COUNT(&set) != 2) std::abort();
    return cpus;
}

inline void pin(int cpu) {
    cpu_set_t set;
    CPU_ZERO(&set);
    CPU_SET(cpu, &set);
    if (pthread_setaffinity_np(pthread_self(), sizeof(set), &set)) std::abort();
}

inline constexpr std::uint64_t kRounds = 20'000;

}  // namespace mm_regime

// Round trips of a cache line of a region between the launch's two CPUs; the
// reported time per item is one round trip. Arguments: kind, index, mode.
// Modes 0, 1 and 2 use line 0, 1 or 2 of the region: thread A writes 2k+1 and
// waits for 2k+2, thread B waits for 2k+1 and writes 2k+2. Mode 3 uses two
// lines, as the producer and consumer of a one-slot ring would: A writes line 1
// and waits on line 0, B waits on line 1 and writes line 0. The regions hold
// no live queue while this runs; the next queue benchmark rebuilds its own.
static void BM_LineRoundTrip(benchmark::State& state) {
    char* const base = static_cast<char*>(mm_regime::g_regions[state.range(0)][state.range(1)]);
    const std::int64_t mode = state.range(2);
    auto* const a_line = reinterpret_cast<std::atomic<std::uint64_t>*>(base + 64 * (mode == 3 ? 1 : mode));
    auto* const b_line = reinterpret_cast<std::atomic<std::uint64_t>*>(base + 64 * (mode == 3 ? 0 : mode));
    const std::array<int, 2> cpus = mm_regime::launch_cpus();
    for (auto _ : state) {
        a_line->store(0, std::memory_order_relaxed);
        b_line->store(0, std::memory_order_relaxed);
        std::atomic<int> ready{0};
        double seconds = 0;
        std::thread b([&ready, a_line, b_line, cpu = cpus[1]] {
            mm_regime::pin(cpu);
            ready.fetch_add(1);
            while (ready.load() < 2) {}
            for (std::uint64_t k = 0; k < mm_regime::kRounds; ++k) {
                while (a_line->load(std::memory_order_acquire) != 2 * k + 1) {}
                b_line->store(2 * k + 2, std::memory_order_release);
            }
        });
        std::thread a([&ready, &seconds, a_line, b_line, cpu = cpus[0]] {
            mm_regime::pin(cpu);
            ready.fetch_add(1);
            while (ready.load() < 2) {}
            const auto start = std::chrono::steady_clock::now();
            for (std::uint64_t k = 0; k < mm_regime::kRounds; ++k) {
                a_line->store(2 * k + 1, std::memory_order_release);
                while (b_line->load(std::memory_order_acquire) != 2 * k + 2) {}
            }
            seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        });
        a.join();
        b.join();
        state.SetIterationTime(seconds);
    }
    state.SetItemsProcessed(static_cast<std::int64_t>(state.iterations() * mm_regime::kRounds));
}
// Kinds 0 (int64 ring) and 1 (Order ring): head_ line, tail_ line, both as a
// one-slot ring. Kind 3 (mutex queue state): its first three lines.
BENCHMARK(BM_LineRoundTrip)
    ->ArgsProduct({{0, 1}, benchmark::CreateDenseRange(0, 7, 1), {0, 1, 3}})
    ->Iterations(10)
    ->UseManualTime();
BENCHMARK(BM_LineRoundTrip)
    ->ArgsProduct({{3}, benchmark::CreateDenseRange(0, 7, 1), {0, 1, 2}})
    ->Iterations(10)
    ->UseManualTime();
'''


