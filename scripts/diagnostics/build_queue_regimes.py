                 '            int64_t diag_received = 0, diag_sum = 0;  // DIAG\n'
                 '            Order o{};\n'
                 '            while (diag_received < N) {  // DIAG\n'
                 '                if (buf.try_pop(o)) {\n'
                 '                    diag_sum += o.price;  // DIAG\n'
                 '                    ++diag_received;  // DIAG\n'
                 '                } else [[unlikely]] {  // DIAG\n'
                 '                    diag_probe.fail(diag_received);  // DIAG\n'
