#!/usr/bin/env python3
"""Build the diagnostic program of the queue-regimes study.

bench_queue_regimes is generated from the unchanged
benchmarks/bench_spsc_ring_buffer.cpp by exact text replacements, each of which
must match the expected number of times, and is compiled with the flags and
link inputs of the Release tree. It asks why the producer-to-consumer
benchmarks run at a level set by the memory their queue lands in.

At start-up the program maps and populates eight memory regions of each kind
(int64 ring, Order ring, Order source array, mutex queue state, int64 locals).
Every two-thread benchmark takes a region index as its last argument and builds
its queue at the start of that region, so one launch measures eight placements
and the benchmarks that share an index share the same memory.

BM_SPSC_ProducerConsumer          int64 ring; the checksum and done flag in the
                                  locals region, as in the earlier counters study
BM_SPSC_Local_ProducerConsumer    copy of it; the consumer sums into a local
                                  and N is captured by value
BM_SPSCCached_ProducerConsumer    copy of the Local family on a ring that caches
                                  the other side's index (mm_regime::CachedRing)
BM_SPSC_Order_ProducerConsumer    Order ring, source array in its own region,
                                  consumer counts and sums into locals
BM_SPSCCached_Order_ProducerConsumer  copy of it on the cached ring
BM_Mutex_ProducerConsumer         mutex queue state at the start of its region
BM_LineRoundTrip                  round trips of one cache line of a region
                                  between the launch's two CPUs

The two-thread benchmarks count, per item, the tries that found the queue empty
(pop) or full (push) and the items before which a side had to retry, and report
the queue depth when the producer finished. In the copied families the lines
that differ from the original end in "// DIAG"; every other added or changed
line does too. The generated sources, commands and hashes are written beside
the binary in build/diagnostics/regimes/.

Requires an already built CMake Unix Makefiles Release tree.
"""

