#!/usr/bin/env python3
"""Build an opt-in copy of the mutex benchmark with controlled object placement.

The original benchmark and engine sources remain the inputs to the normal build.
This diagnostic changes only the throughput benchmark's local engine storage and
logs its address before Google Benchmark starts timing the state loop. Set
MM_MUTEX_OFFSET to 0, 16, 32 or 48 in each diagnostic process. The generated
source, commands and hashes are retained beside the diagnostic binary.

Requires an already built CMake Unix Makefiles Release tree. It reuses that
tree's compiler, preprocessor flags, compiler flags and link inputs.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shlex
import subprocess


HELPER = r'''
// Diagnostic local storage; the MutexMatchingEngine definition is unchanged.
class MutexLayoutStorage {
public:
    MutexLayoutStorage() {
        const char* value = std::getenv("MM_MUTEX_OFFSET");
        size_t offset = 0;
        if (value && std::strcmp(value, "0") == 0) offset = 0;
        else if (value && std::strcmp(value, "16") == 0) offset = 16;
        else if (value && std::strcmp(value, "32") == 0) offset = 32;
        else if (value && std::strcmp(value, "48") == 0) offset = 48;
        else {
            std::fprintf(stderr, "MM_MUTEX_OFFSET must be 0, 16, 32 or 48\n");
            std::abort();
        }
        static_assert(alignof(MutexMatchingEngine) <= 16);
        engine_ = ::new (static_cast<void*>(storage_ + offset)) MutexMatchingEngine;
        const auto address = reinterpret_cast<std::uintptr_t>(engine_);
        std::fprintf(stderr,
            "MM_LAYOUT address=%p mod64=%zu mod4096=%zu size=%zu align=%zu offset=%zu\n",
            static_cast<void*>(engine_), static_cast<size_t>(address % 64),
            static_cast<size_t>(address % 4096), sizeof(MutexMatchingEngine),
            alignof(MutexMatchingEngine), offset);
    }

    ~MutexLayoutStorage() { std::destroy_at(engine_); }
    MutexLayoutStorage(const MutexLayoutStorage&) = delete;
    MutexLayoutStorage& operator=(const MutexLayoutStorage&) = delete;
    MutexMatchingEngine& get() noexcept { return *engine_; }

private:
    alignas(64) unsigned char storage_[sizeof(MutexMatchingEngine) + 64];
    MutexMatchingEngine* engine_ = nullptr;
};

'''


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path, default=root / "build/release")
    parser.add_argument("--output", type=Path, default=root / "build/mutex-layout")
    args = parser.parse_args()
    build = args.build.resolve()
    output = args.output.resolve()
    source = root / "benchmarks/bench_baseline_mutex.cpp"
    target = build / "CMakeFiles/bench_baseline_mutex.dir"

    flags_text = (target / "flags.make").read_text()
    flags = {}
    for name in ("DEFINES", "INCLUDES", "FLAGS"):
        match = re.search(rf"^CXX_{name} = (.*)$", flags_text, re.MULTILINE)
        if not match:
            raise SystemExit(f"CXX_{name} absent from {target / 'flags.make'}")
        flags[name] = shlex.split(match.group(1))
    link_text = (target / "link.txt").read_text()
    original_link = shlex.split(link_text)
    original_object = "CMakeFiles/bench_baseline_mutex.dir/benchmarks/bench_baseline_mutex.cpp.o"
    if original_link.count(original_object) != 1:
        raise SystemExit("Expected one original mutex benchmark object in link.txt")

    text = source.read_text()
    marker = "static void BM_MutexPipeline_Throughput(benchmark::State& state) {"
    if text.count(marker) != 1:
        raise SystemExit("Cannot identify the original throughput function uniquely")
    prefix, function = text.split(marker, 1)
    original = "    MutexMatchingEngine engine;\n    for (auto _ : state) {"
    if not function.startswith("\n") or original not in function:
        raise SystemExit("Cannot identify original throughput local storage")
    function = function.replace(original,
        "    MutexLayoutStorage storage;\n"
        "    MutexMatchingEngine& engine = storage.get();\n"
        "    for (auto _ : state) {", 1)
    generated_text = (
        "// Generated by scripts/diagnostics/build_mutex_layout.py.\n"
        "// Diagnostic placement experiment; not a replacement benchmark.\n"
        "#include <cstdlib>\n#include <cstdint>\n#include <new>\n"
        + prefix + HELPER + marker + function)

    output.mkdir(parents=True, exist_ok=True)
    generated = output / "bench_mutex_layout.cpp"
    obj = output / "bench_mutex_layout.o"
    binary = output / "bench_mutex_layout"
    generated.write_text(generated_text)
    compile_cmd = [original_link[0], *flags["DEFINES"], *flags["INCLUDES"],
                   *flags["FLAGS"], "-o", str(obj), "-c", str(generated)]
    link_cmd = []
    output_next = False
    for token in original_link:
        if output_next:
            link_cmd.append(str(binary))
            output_next = False
        elif token == "-o":
            link_cmd.append(token)
            output_next = True
        elif token == original_object:
            link_cmd.append(str(obj))
        elif token.startswith("-Wl,--dependency-file="):
            link_cmd.append(f"-Wl,--dependency-file={output / 'link.d'}")
        else:
            link_cmd.append(token)

    metadata = {
        "purpose": "diagnostic object placement; workload and class definition unchanged",
        "git_commit": subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=root, text=True).strip(),
        "source": str(source), "source_sha256": sha256(source),
        "generated_source": str(generated), "generated_sha256": sha256(generated),
        "working_directory": str(build), "original_flags_make": flags_text,
        "original_link_command": original_link,
        "compile_command": compile_cmd, "link_command": link_cmd,
        "offset_environment_variable": "MM_MUTEX_OFFSET",
        "allowed_offsets_bytes": [0, 16, 32, 48],
    }
    metadata_path = output / "build.json"
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")
    subprocess.run(compile_cmd, cwd=build, check=True)
    subprocess.run(link_cmd, cwd=build, check=True)
    metadata["binary_sha256"] = sha256(binary)
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")
    print(binary)
    print(f"Build provenance: {metadata_path}")


if __name__ == "__main__":
    main()
